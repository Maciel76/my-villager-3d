test("the animated sky beam has a separate lifetime and leaves the monument's building bounds finite", () => {
  const monument = createConvergencia();
  const scene = new THREE.Scene();
  const animation = createConvergenceAnimation(scene);
  const camera = new THREE.PerspectiveCamera(47, 16 / 9, 0.5, 420);
  const construction = new Set();
  camera.position.set(38, 84, 245);
  camera.lookAt(6, 60, -17);
  monument.position.set(6, 2, -17);
  monument.rotation.y = Math.PI / 2;
  scene.add(monument);
  animation.add(monument);
  const effects = scene.getObjectByName("Luz da Convergência");
  const beam = effects.getObjectByName("Feixe até o céu");
  const orbit = effects.getObjectByName("Órbita 1");
  const bounds = new THREE.Box3().setFromObject(monument);

  assert.deepEqual(footprint("convergencia"), [72, 72]);
  assert.ok(bounds.max.y < 44);
  assert.ok(beam.geometry.parameters.height > camera.far);
  assert.ok(Math.abs(beam.position.y + beam.geometry.parameters.height / 2 - convergence.beamHeight) < .01);
  assert.equal(animation.update(camera, 2000, construction, true), true);
  assert.deepEqual(effects.position.toArray(), monument.position.toArray());
  const firstAngle = orbit.rotation.y;
  animation.update(camera, 3200, construction, true);
  assert.notEqual(orbit.rotation.y, firstAngle);
  assert.equal(animation.update(camera, 4200, construction, false), false);
  const frozenAngle = orbit.rotation.y;
  animation.update(camera, 5200, construction, false);
  assert.equal(orbit.rotation.y, frozenAngle);

  construction.add(monument);
  assert.equal(animation.update(camera, 6200, construction, true), false);
  assert.equal(effects.visible, false);
  construction.delete(monument);
  monument.visible = false;
  assert.equal(animation.update(camera, 7200, construction, true), false);

  animation.remove(monument);
  assert.equal(scene.getObjectByName("Luz da Convergência"), undefined);
  assert.equal(animation.update(camera, 8200, construction, true), false);
});

test("stellar choreography launches the globe before the burst and keeps the remnant at 90 seconds", () => {
  const timeline = createStellarTimeline();
  assert.equal(timeline.sample(0).reflector, 0);
  assert(timeline.sample(5).reflector > 0);
  const aligning = timeline.sample(STELLAR_LIFT_START - 3);
  assert(aligning.ringAlignment > 0 && aligning.ringAlignment < 1 && aligning.lift === 0);
  const aligned = timeline.sample(STELLAR_LIFT_START - .5);
  assert.equal(aligned.ringAlignment, 1);
  assert.equal(aligned.lift, 0);
  assert.equal(aligned.ringSpacing, 0);
  const rising = timeline.sample(STELLAR_LIFT_START + 2);
  assert(rising.ringAlignment === 1 && rising.lift > 0);
  const loading = timeline.sample(STELLAR_LAUNCH - 1);
  assert.equal(loading.ringSpacing, 1);
  assert.equal(loading.ringThrust, 0);
  const pushing = timeline.sample(STELLAR_LAUNCH - .02);
  assert.equal(pushing.ringThrust, 1);
  assert.equal(pushing.launch, 0);
  assert(pushing.ringDischarge > .5);
  assert(timeline.sample(45).doors > 0);
  assert.equal(timeline.sample(STELLAR_LAUNCH).lift, 1);
  assert.equal(timeline.sample(STELLAR_LAUNCH).launch, 0);
  assert.equal(timeline.sample(STELLAR_LAUNCH).arms, 1);
  assert(timeline.sample(STELLAR_LAUNCH).darkness > .95);
  assert(timeline.sample(STELLAR_ARRIVAL).launch > .999);
  assert.equal(timeline.sample(STELLAR_ARRIVAL).flare, 0);
  assert.equal(timeline.sample(STELLAR_ARRIVAL + .35).darkness, 0);
  assert(timeline.sample(STELLAR_BURST + .17).flare > .95);
  assert(timeline.sample(STELLAR_BURST + .5).dayFlash > .95);
  assert(timeline.sample(STELLAR_BURST + 1.95).dayFlash > .9);
  assert.equal(timeline.sample(STELLAR_WAVES[1].start).dayFlash, 0);
  const wavePeaks = STELLAR_WAVES.map(({ start }, index) => {
    const { waves, nebula } = timeline.sample(start + .3);
    assert.equal(nebula, 0);
    assert.equal(waves.filter(wave => wave.power > 0).length, 1);
    assert(waves[index].radius > 0);
    return waves[index].power;
  });
  assert.equal(wavePeaks.length, 3);
  assert(wavePeaks[0] > wavePeaks[1] && wavePeaks[1] > wavePeaks[2] && wavePeaks[2] > .2);
  assert.equal(timeline.sample(STELLAR_WAVE_END).nebula, 0);
  assert(timeline.sample(STELLAR_WAVE_END).waves.every(wave => wave.radius > Math.PI && wave.power === 0));
  assert(timeline.sample(STELLAR_WAVE_END + .5).nebula > 0);
  const final = timeline.sample(STELLAR_SHUTDOWN);
  assert.deepEqual([final.reflector, final.charge, final.crown, final.nebula], [0, 0, 0, 1]);
  assert.equal(final.darkness, 0);
  assert.equal(final.ringAlignment, 1);
  assert.equal(final.ringSpacing, 0);
  assert.equal(final.ringThrust, 0);
  assert.equal(timeline.sample(STELLAR_ORBITS_DESCENT_START).ringDescent, 0);
  assert.equal(timeline.sample(STELLAR_ORBITS_DOCKED).ringDescent, 1);
  assert.equal(timeline.sample(STELLAR_ORBITS_DOCKED).crownDescent, 0);
  assert.equal(timeline.sample(STELLAR_DURATION).crownDescent, 1);
  assert.equal(timeline.sample(0).nebula, 0);
});

test("reactivation grows the core as each ring rises from smallest to largest, followed by the crown and beam", () => {
  const timeline = createStellarTimeline();
  assert.equal(timeline.reactivationPose(0).core, 0);
  const early = timeline.reactivationPose(1.5);
  assert(early.core > 0 && early.core < .09);
  assert(early.orbits[2].lift > 0 && early.orbits[1].lift === 0 && early.orbits[0].lift === 0);
  assert.deepEqual(timeline.reactivationPose(4).orbits.map(ring => ring.lift), [0, 0, 1]);
  assert(timeline.reactivationPose(5).orbits[2].turn > 4);
  assert.deepEqual(timeline.reactivationPose(7).orbits.map(ring => ring.lift), [0, 1, 1]);
  assert(timeline.reactivationPose(9).orbits[1].turn > 8);
  const stable = timeline.reactivationPose(13.2);
  assert.deepEqual(stable.orbits.map(ring => ring.lift), [1, 1, 1]);
  assert.deepEqual([stable.core, stable.crownLift, stable.crownLight, stable.beam], [1, 0, 0, 0]);
  const darkCrown = timeline.reactivationPose(17.5);
  assert.deepEqual([darkCrown.crownLift, darkCrown.crownLight, darkCrown.beam], [1, 0, 0]);
  const litCrown = timeline.reactivationPose(18.9);
  assert.deepEqual([litCrown.crownLight, litCrown.beam], [1, 0]);
  assert(timeline.reactivationPose(20).beam > 0 && timeline.reactivationPose(20).beam < 1);
  assert(timeline.reactivationPose(17.5).arms > timeline.reactivationPose(13.2).arms);
  assert.equal(timeline.reactivationPose(STELLAR_REACTIVATION_DURATION).arms, 0);
});

test("the city blackout cuts all electric lighting and restores the previous settings", () => {
  const city = new THREE.Group();
  const streetLamp = markNightLight(new THREE.MeshStandardMaterial(), 2);
  const sign = new THREE.MeshStandardMaterial({ emissive: "#ffffff", emissiveIntensity: .8 });
  const window = new THREE.MeshStandardMaterial({ envMap: new THREE.Texture(), envMapIntensity: .65 });
  city.add(new THREE.Mesh(new THREE.BoxGeometry(), [streetLamp, sign, window]));
  const scene = new THREE.Scene();
  scene.fog = new THREE.Fog("#ffffff", 30, 150);
  const daylight = createDaylight(scene, { shadowMap: {} }, { city });
  daylight.setHour(23);
  assert.equal(daylight.lampPower, 1);
  assert.equal(streetLamp.emissiveIntensity, 2);
  assert.equal(daylight.setStellarLighting(true, .99, 0), true);
  assert.equal(daylight.lampPower, 0);
  assert.equal(streetLamp.emissiveIntensity, 0);
  assert.equal(sign.emissiveIntensity, 0);
  assert(window.envMapIntensity < .05);
  assert(daylight.sky.material.uniforms.skyExposure.value < .03);
  const blast = scene.getObjectByName("Clarão da Explosão Estelar");
  daylight.setStellarLighting(true, 0, 1, new THREE.Vector3(9, 3, 17));
  assert.equal(daylight.sky.material.uniforms.stellarFlash.value, 1);
  assert.deepEqual(blast.position.toArray(), [9, 3 + convergence.beamHeight, 17]);
  assert(blast.intensity > 2.4);
  assert.equal(daylight.lampPower, 0);
  assert.equal(streetLamp.emissiveIntensity, 0);
  daylight.setStellarLighting(true, 0, 0);
  assert.equal(blast.intensity, 0);
  assert.equal(daylight.sky.material.uniforms.stellarFlash.value, 0);
  daylight.setHour(12);
  assert.equal(daylight.setStellarLighting(true, 0, 0), false);
  assert.equal(sign.emissiveIntensity, 0);
  assert.equal(daylight.sky.material.uniforms.skyExposure.value, 1);
  daylight.setHour(23);
  assert.equal(daylight.setStellarLighting(false, 0, 0), true);
  assert.deepEqual([daylight.lampPower, streetLamp.emissiveIntensity, sign.emissiveIntensity, window.envMapIntensity],
    [1, 2, .8, .65]);
});

test("stellar activation survives the village save and belongs only to the Convergence", () => {
  const stellarAt = 1_800_000_000_000;
  const plaza = { x: 6, z: 6, type: "convergencia", rotation: 0 };
  const world = { version: 1, houses: [{ ...plaza, stellarAt }] };
  assert(isVillageWorld(world));
  assert.equal(readSave(world)[0].stellarAt, stellarAt);
  assert(isVillageWorld({ version: 1, houses: [plaza] }));
  assert(!isVillageWorld({ version: 1, houses: [{ ...plaza, stellarAt: -1 }] }));
  assert(!isVillageWorld({ version: 1, houses: [{ ...plaza, type: "cottage", stellarAt }] }));
  assert(isVillageWorld({ version: 1, houses: [], stellarSkyAt: stellarAt }));
  assert(!isVillageWorld({ version: 1, houses: [], stellarSkyAt: -1 }));
  assert(isVillageWorld({ version: 1, houses: [], stellarSkyAt: null, convergenceReserve: { stellarAt } }));
  assert(isVillageWorld({ version: 1, houses: [], convergenceReserve: { stellarReactivatedAt: stellarAt } }));
  assert(!isVillageWorld({ ...world, convergenceReserve: {} }));
  assert(!isVillageWorld({ version: 1, houses: [], convergenceReserve: { stellarAt, stellarReactivatedAt: stellarAt } }));
  const rearmed = { version: 1, houses: [{ ...plaza, stellarReactivatedAt: stellarAt }] };
  assert(isVillageWorld(rearmed));
  assert.equal(readSave(rearmed)[0].stellarReactivatedAt, stellarAt);
  assert(stellarBusy(rearmed.houses[0], stellarAt + 1000));
  assert(stellarBusy(rearmed.houses[0], stellarAt + STELLAR_REACTIVATION_DURATION * 1000));
  assert(stellarBusy(rearmed.houses[0], stellarAt + STELLAR_REACTIVATION_TOTAL * 1000 - 1));
  assert(!stellarBusy(rearmed.houses[0], stellarAt + STELLAR_REACTIVATION_TOTAL * 1000));
  assert(isStellarNight("23"));
  assert(!isStellarNight("18"));
  assert(stellarInProgress(stellarAt, stellarAt + STELLAR_EVENT_DURATION * 1000 - 1));
  assert(!stellarInProgress(stellarAt, stellarAt + STELLAR_EVENT_DURATION * 1000));
});

test("a spent Convergence parks the rings and stops emitting light while another one stays powered", () => {
  const template = createConvergencia();
  const unlit = createUnlitConvergence(template);
  const scene = new THREE.Scene();
  const camera = new THREE.PerspectiveCamera(47, 16 / 9, .5, 500);
  camera.position.set(0, 70, 280);
  camera.lookAt(0, 100, 0);
  const spent = template.clone();
  const idle = template.clone();
  idle.position.x = 140;
  scene.add(spent, idle);
  const houses = [spent, idle].map(model => ({ model, type: "convergencia" }));
  const clock = 1_800_000_000_000;
  const showStart = clock + STELLAR_DRAIN_DURATION * 1000;
  const cutoff = showStart + STELLAR_SHUTDOWN * 1000;
  const finish = clock + STELLAR_EVENT_DURATION * 1000;
  const construction = new Set();
  const fx = createConvergenceAnimation(scene, createStellarTimeline(), unlit.materials);
  const lights = createNightLights(scene, { clustered: true });
  fx.add(spent, clock);
  fx.update(camera, 0, construction, true, showStart - 1000);
  assert.equal(scene.getObjectByName("Explosão Estelar"), undefined);
  assert.equal(scene.getObjectByName("Luz do mini-sol").intensity, 0);
  const effects = scene.getObjectByName("Luz da Convergência");
  const crown = effects.getObjectByName("Coroa de luz");
  const sun = effects.getObjectByName("Mini-sol");
  const orbits = [1, 2, 3].map(i => effects.getObjectByName(`Órbita ${i}`));
  const horizontal = () => orbits.every(orbit => orbit.rotation.x === 0 && orbit.rotation.z === 0);
  const heightsAt = elapsed => {
    const time = Math.round(elapsed * 1000);
    fx.update(camera, time, construction, true, showStart + time);
    return orbits.map(orbit => orbit.position.y);
  };
  fx.update(camera, 33000, construction, true, showStart + (STELLAR_LIFT_START - 7) * 1000);
  assert(orbits.every(orbit => orbit.rotation.z !== 0));
  const usualHeight = heightsAt(STELLAR_LIFT_START - .5);
  assert(horizontal());
  assert(usualHeight.every(height => height === convergence.sunY));
  assert.equal(sun.position.y, convergence.sunY);
  const alignedYaw = orbits.map(orbit => orbit.rotation.y);
  const prepared = heightsAt(STELLAR_LAUNCH - 1);
  assert(prepared[0] > convergence.sunY && prepared[1] < convergence.sunY && prepared[2] < prepared[1]);
  const raised = heightsAt(STELLAR_LAUNCH - .02);
  const travel = raised.map((height, index) => height - prepared[index]);
  assert(travel[0] > 0 && travel[0] < travel[1] && travel[1] < travel[2]);
  assert(raised[0] < raised[1] && raised[1] < raised[2]);
  assert(raised[2] < sun.position.y && sun.position.y - raised[2] < 3);
  assert(sun.position.y <= STELLAR_LIFT_HEIGHT);
  assert.equal(effects.getObjectByName("Impulso de luz").visible, true);
  const recovering = heightsAt(STELLAR_BURST + 2);
  assert(recovering.every((height, index) => height < raised[index] && height > usualHeight[index]));
  assert.deepEqual(heightsAt(STELLAR_BURST + 6), usualHeight);
  heightsAt(STELLAR_ARRIVAL);
  assert(horizontal());
  assert.equal(sun.position.y, convergence.beamHeight);
  assert(orbits.every((orbit, index) => orbit.rotation.y !== alignedYaw[index]));
  assert.equal(fx.syncPower(cutoff - 1), false);
  assert.equal(fx.syncPower(cutoff), true);
  assert.equal(fx.syncPower(cutoff + 1), false);
  assert.equal(spent.userData.lampEmitters, undefined);
  assert.equal(fx.update(camera, 90000, construction, true, cutoff), true);
  const yaw = orbits.map(orbit => orbit.rotation.y);
  fx.update(camera, 95000, construction, true, showStart + STELLAR_ORBITS_DESCENT_START * 1000);
  assert(horizontal());
  assert.deepEqual(orbits.map(orbit => orbit.rotation.y), yaw);
  fx.update(camera, 101000, construction, true, showStart + STELLAR_ORBITS_DOCKED * 1000);
  assert(orbits.every(orbit => orbit.position.y < 5));
  assert.equal(crown.position.y, convergence.crownY);
  assert.equal(fx.update(camera, 90000, construction, true, finish), false);
  assert(crown.position.y < 5);
  const parked = [crown, ...orbits];
  const poses = parked.map(part => part.matrix.toArray());
  fx.update(camera, 98000, construction, true, finish + 8000);
  assert.deepEqual(parked.map(part => part.matrix.toArray()), poses);
  assert.equal(effects.getObjectByName("Feixe até o céu").visible, false);
  assert.equal(effects.getObjectByName("Cascatas iluminadas").visible, false);
  assert.equal(effects.getObjectByName("Explosão Estelar").visible, false);

  lights.update(houses, camera, 1);
  assert.equal(lights.stats.emitters, template.userData.lampEmitters.length);
  const poweredFixtures = [];
  idle.traverse(part => { if (part.material?.userData.nightGlow) poweredFixtures.push(part.material); });
  assert(poweredFixtures.length > 0);
  spent.traverse(part => assert(!part.material?.userData.nightGlow));

  fx.setEvent(spent, undefined, finish);
  fx.update(camera, 0, construction, true, finish + 6000);
  const arms = spent.children.filter(part => part.userData.hinge);
  const siteLight = scene.getObjectByName("Luz do mini-sol");
  assert.equal(arms.length, 6);
  assert(arms.every(part => part.quaternion.w < 1));
  assert(crown.position.y < 5);
  assert(sun.scale.x < .6);
  fx.update(camera, 0, construction, true, finish + 17500);
  assert(siteLight.intensity > 10000);
  const bright = siteLight.intensity;
  fx.update(camera, 20000, construction, true, finish + 20000);
  assert(siteLight.intensity > 0 && siteLight.intensity < bright);
  assert.equal(fx.syncPower(finish + STELLAR_RELIGHT * 1000), true);
  lights.update(houses, camera, 1);
  assert.equal(lights.stats.emitters, template.userData.lampEmitters.length * 2);
  fx.update(camera, 0, construction, true, finish + STELLAR_REACTIVATION_DURATION * 1000);
  assert(arms.every(part => part.quaternion.w === 1));
  assert.equal(siteLight.intensity, 0);
  assert.equal(sun.visible, true);
  assert.equal(effects.getObjectByName("Feixe até o céu").visible, true);
  const rotationAt = elapsed => {
    const time = Math.round(elapsed * 1000);
    fx.update(camera, time, construction, true, finish + time);
    return [sun, ...orbits, crown].map(part => part.rotation.y);
  };
  for (const [from, to] of [[14, 15], [21.95, 22], [22, 22.05]]) {
    const before = rotationAt(from);
    const after = rotationAt(to);
    [.297, .27, -.33, .48, -.115].forEach((speed, index) => {
      assert(Math.abs((after[index] - before[index]) / (to - from) - speed) < 1e-5);
    });
  }

  fx.setEvent(spent, finish, undefined);
  const nextShow = finish + STELLAR_DRAIN_DURATION * 1000;
  fx.update(camera, 0, construction, true, nextShow + 25500);
  const gates = effects.getObjectByName("Anéis da escada estelar");
  assert.equal(gates.children.filter(part => part.visible).length, 1);
  fx.update(camera, 0, construction, true, nextShow + 26900);
  assert.equal(gates.children.filter(part => part.visible).length, 2);
  fx.update(camera, 0, construction, true, nextShow + 38500);
  const half = gates.children.filter(part => part.visible);
  assert.equal(half.length, 8);
  assert.deepEqual(half, gates.children.slice(0, 8));
  fx.update(camera, 0, construction, true, nextShow + Math.round(STELLAR_LAUNCH * 1000));
  assert.equal(gates.children.filter(part => part.visible).length, 17);
  const heights = gates.children.map(part => part.position.y);
  assert(heights[0] > convergence.crownY && heights[0] < STELLAR_LIFT_HEIGHT + 20);
  assert(heights.slice(1).every((height, index) => {
    const gap = height - heights[index];
    return gap > 33 && gap < 40;
  }));
  assert.equal(heights.at(-1), convergence.beamHeight);
  assert.equal(sun.position.y, STELLAR_LIFT_HEIGHT);
  assert(sun.position.y > convergence.crownY && sun.position.y < convergence.crownY + 8);
  assert(arms.every(part => part.quaternion.w < .997));
  assert(siteLight.intensity > 15000);
  assert.deepEqual(siteLight.position.toArray(), sun.getWorldPosition(new THREE.Vector3()).toArray());
  const startingRange = siteLight.distance;
  fx.update(camera, 0, construction, true, nextShow + Math.round((STELLAR_LAUNCH + .4) * 1000));
  assert(siteLight.position.y > 200 && siteLight.distance > startingRange && siteLight.intensity > 15000);
  assert.deepEqual(siteLight.position.toArray(), sun.getWorldPosition(new THREE.Vector3()).toArray());
  fx.update(camera, 0, construction, true, nextShow + Math.round(STELLAR_ARRIVAL * 1000));
  assert.equal(effects.getObjectByName("Mini-sol").position.y, convergence.beamHeight);
  assert.equal(effects.getObjectByName("Mini-sol").visible, true);
  assert(gates.children.at(-1).children[0].material.opacity > gates.children[0].children[0].material.opacity);
  fx.update(camera, 0, construction, true, nextShow + Math.round((STELLAR_BURST + .2) * 1000));
  assert.equal(effects.getObjectByName("Mini-sol").visible, false);
  const blast = effects.getObjectByName("Explosão no alto do feixe");
  assert.equal(blast.position.y, convergence.beamHeight);
  assert.equal(blast.visible, true);
});
